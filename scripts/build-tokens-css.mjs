#!/usr/bin/env node
/**
 * Builds dist/tokens.css — a self-contained resolution of every --ds-*
 * variable src/styles/variables.css maps from @mellon-design/tokens-web.
 *
 * This is deliberately a separate build output from dist/style.css
 * (produced by `vite build`), not merged into it: dist/style.css is pure
 * component CSS (consumes var(--ds-*) everywhere, defines nothing), and
 * this file is the optional, explicitly-imported piece that actually
 * defines those variables. See CLAUDE.md's "src/styles/ never enters the
 * library build" note for why that split is deliberate — folding this
 * into every consumer's bundle unconditionally would force this
 * package's specific light/dark/high-contrast choices onto apps that
 * already wire up their own theming.
 *
 * Runs after `vite build` (see package.json's "build" script). Uses
 * Node's own `require.resolve` (via createRequire), not a CSS bundler
 * plugin, to resolve @mellon-design/tokens-web's package.json `exports`
 * map — the same resolution algorithm Node itself uses, so it can't
 * drift from how the package actually resolves at install time.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = process.cwd();

// Mirrors the four @import lines at the top of src/styles/variables.css.
const TOKEN_IMPORTS = [
  '@mellon-design/tokens-web/css',
  '@mellon-design/tokens-web/css/theme-light',
  '@mellon-design/tokens-web/css/theme-dark',
  '@mellon-design/tokens-web/css/theme-high-contrast',
];

const resolvedTokensCss = TOKEN_IMPORTS.map((specifier) =>
  readFileSync(require.resolve(specifier), 'utf8'),
).join('\n');

const variablesCssPath = path.join(ROOT, 'src/styles/variables.css');
const variablesCss = readFileSync(variablesCssPath, 'utf8');

// The @import lines are already inlined above (as the real files, not a
// runtime @import a consumer's bundler would need to re-resolve) — strip
// them so they aren't duplicated in the output.
const mappingCss = variablesCss
  .split('\n')
  .filter((line) => !line.trim().startsWith("@import '@mellon-design/tokens-web"))
  .join('\n')
  .trim();

const banner = `/*
 * @mellon-design/react/tokens.css — generated by scripts/build-tokens-css.mjs, do not edit directly.
 *
 * Defines every --ds-* CSS variable this library's components reference,
 * resolved from @mellon-design/tokens-web. Import this alongside
 * @mellon-design/react/styles.css:
 *
 *   import '@mellon-design/react/styles.css';
 *   import '@mellon-design/react/tokens.css';
 *
 * Light is the unconditional default; set data-theme="dark" or
 * data-theme="high-contrast" on any ancestor element to switch.
 * Already wiring up your own token layer? Skip this file — styles.css
 * has no dependency on it beyond the --ds-* variable names.
 */
`;

const outPath = path.join(ROOT, 'dist/tokens.css');
mkdirSync(path.dirname(outPath), { recursive: true });
writeFileSync(outPath, `${banner}\n${resolvedTokensCss}\n\n${mappingCss}\n`);

console.log(`Built dist/tokens.css (${TOKEN_IMPORTS.length} token files + variable mapping)`);
